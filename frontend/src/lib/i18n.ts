const dictionaries: Record<'en' | 'fr', Dict> = { en, fr };

function resolve(dict: Dict, path: string): string | undefined {
  return path.split('.').reduce<unknown>((acc, key) => (acc && typeof acc === 'object' ? (acc as Record<string, unknown>)[key] : undefined), dict) as
    | string
    | undefined;
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(params[key] ?? ''));
}

export function useT() {
  const locale = useLocaleStore((s) => s.locale);
  return (path: string, params?: Record<string, string | number>): string => {
    const template = resolve(dictionaries[locale], path) ?? resolve(dictionaries.en, path) ?? path;
    return interpolate(template, params);
  };
}

/** For the rare case a component needs a translated list (e.g. sample search chips), not a single string. */
export function useDict(): Dict {
  const locale = useLocaleStore((s) => s.locale);
  return dictionaries[locale];
}
